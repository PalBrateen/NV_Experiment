"""
Example: Using YAML Configuration Files

This example shows how to run experiments using YAML config files
instead of Python config files.

Benefits of YAML configs:
- Human-readable format
- Easy to edit without Python knowledge
- Version control friendly
- Can be generated by GUI
- Shareable across different systems

Date: 16 December 2024
"""

from mainControl import run_sweep_experiment, load_experiment_config
from SGcontrol import SignalGenerator, SignalGenerator_sim
from PBcontrol import PulseBlaster
from DAQcontrol import AnalogInputTask
import connectionConfig as concfg, matplotlib.pyplot as plt
# %matplotlib qt

# ============================================================================
# METHOD 1: Load YAML config and run experiment
# ============================================================================

def run_esr_from_yaml():
    """Run ESR experiment from YAML config file."""

    print("\n" + "="*70)
    print(" "*20 + "ESR from YAML Config")
    print("="*70)

    # Load YAML config - automatically detects format!
    params_dict = load_experiment_config('configs/esr_config.yaml')

    # Initialize instruments
    instruments = {
        'sg': SignalGenerator_sim(name="sg1"),  # Simulated for example
        'pb': PulseBlaster(params_dict, name="pb1"),
        'ai_task': AnalogInputTask(
            dev=concfg.daq_dev,
            channels=concfg.input_terminals,
            voltage_range=(-0.2, 0.2),
            sampling_rate=params_dict['daq']['sampling_rate'],
            samps_per_chan=params_dict['daq']['Nsamples'],
            trigger_source=concfg.samp_clk_terminal,
            name="ai_task"
        )
    }

    # Run experiment - ONE LINE!
    results = run_sweep_experiment(params_dict, instruments, mode='diode')

    print(f"\n✓ ESR experiment complete: {len(results)} measurements")
    print(results)
    return results


