# METHOD 3: Programmatic YAML config creation
# ============================================================================

def create_and_save_yaml_config():
    """Create YAML config programmatically and save it."""
    from config_loader import create_esr_config, save_config

    # Create ESR config with custom parameters
    config = create_esr_config(
        freq_start=2.85e9,
        freq_stop=2.89e9,
        freq_step=0.5e6,  # 0.5 MHz steps
        power_dBm=10,
        Nsamples=16,
        Nruns=10,
        t_AOM_us=5000
    )

    # Save to YAML file
    save_config(config, 'configs/my_custom_esr.yaml')

    print("✓ Created and saved custom ESR config to configs/my_custom_esr.yaml")

    # Load it back
    params = load_experiment_config('configs/my_custom_esr.yaml')
    print(f"✓ Loaded back: {params['experiment']['name']}")

    return params


