def mixed_workflow():
    """Load YAML config and modify in Python."""

    # Load base YAML config
    params_dict = load_experiment_config('configs/esr_config.yaml')

    # Modify in Python (e.g., adjust parameters based on previous results)
    import numpy as np
    params_dict['sweep']['frequency'] = np.linspace(2.86e9, 2.88e9, 51)
    params_dict['scan']['Nruns'] = 50

    print("✓ Loaded YAML config and modified in Python")
    print(f"  New frequency range: 2.86 - 2.88 GHz")
    print(f"  New Nruns: 50")

    return params_dict


